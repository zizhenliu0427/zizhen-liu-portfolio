report=[]
for identifier,spec in PLANS.items():
    scene=bpy.data.scenes.new(spec['key']);bpy.context.window.scene=scene
    box(0,1.7,4.12,2.98,'graphite',depth=.025,z=-.016)
    for x in [-2.04,2.04]:
        for y in [.42,3.01]:disc(x,y,.044,'amber',depth=.024,z=.035,part='optical-lenses',vertices=16)
    word(identifier,.25,3.04,.18,1.3)
    word(spec['heading'],-1.87,2.77,.16,3.77)
    word(spec['caption'],-1.87,.50,.106,3.76)
    word('PROFILE RECORD' if identifier[0]=='P' else 'EXPERIENCE RECORD' if identifier[0]=='I' else 'DOCUMENTARY STUDY',-1.87,.27,.086)
    build(spec)
    pairs={}
    for obj in list(scene.objects):pairs.setdefault((obj['assemblyPart'],obj.data.materials[0].name),[]).append(obj)
    for (part,surface),objects in pairs.items():
        bpy.ops.object.select_all(action='DESELECT')
        for obj in objects:obj.select_set(True)
        bpy.context.view_layer.objects.active=objects[0];bpy.ops.object.join()
        obj=bpy.context.object;obj.name=part+'__'+surface;obj['assemblyPart']=part;obj['portfolioInterior']=True
        scene.cursor.location=(0,0,0);bpy.ops.object.origin_set(type='ORIGIN_CURSOR');bpy.ops.object.transform_apply(location=True,rotation=True,scale=True)
    scene['archiveId']=identifier;scene['evidenceSource']='content/archive-exhibits.json'
    bpy.ops.object.select_all(action='SELECT');output=OUTPUT/(spec['key']+'.glb')
    bpy.ops.export_scene.gltf(filepath=str(output),export_format='GLB',use_selection=True,use_active_scene=True,export_apply=True,export_extras=True,export_cameras=False,export_lights=False)
    report.append(dict(id=identifier,key=spec['key'],meshes=len(scene.objects),triangles=sum(len(p.vertices)-2 for obj in scene.objects for p in obj.data.polygons),bytes=output.stat().st_size))
    scene.render.engine='CYCLES';scene.cycles.samples=12
    scene.render.resolution_x=960;scene.render.resolution_y=690;scene.render.resolution_percentage=100
    scene.world=bpy.data.worlds.new('Archive studio');scene.world.use_nodes=True
    scene.world.node_tree.nodes['Background'].inputs[0].default_value=(.12,.15,.17,1);scene.world.node_tree.nodes['Background'].inputs[1].default_value=.4
    scene.view_settings.view_transform='Standard'
    bpy.ops.object.camera_add(location=(.4,-9,4.1));camera=bpy.context.object;camera.rotation_euler=(Vector((0,0,1.75))-camera.location).to_track_quat('-Z','Y').to_euler();camera.data.type='ORTHO';camera.data.ortho_scale=4.7;scene.camera=camera
    for pos,energy,size in [((-3,-4,6),350,4),((3,-2,4),180,3)]:
        bpy.ops.object.light_add(type='AREA',location=pos);light=bpy.context.object;light.data.energy=energy;light.data.shape='DISK';light.data.size=size;light.rotation_euler=(Vector((0,0,1.7))-light.location).to_track_quat('-Z','Y').to_euler()
    scene.render.image_settings.file_format='PNG';scene.render.filepath=str(RENDERS/(spec['key']+'.png'))
    if '--render' in sys.argv:bpy.ops.render.render(write_still=True)
    print('ARCHIVE_EXHIBIT',report[-1],flush=True)
(ROOT/'art/archive-exhibits-report.json').write_text(json.dumps(report,indent=2)+'\n',encoding='utf-8')
