def word(text,x,y,size=.13,width=3.7,part='optical-lenses',material='ceramic'):
    bpy.ops.object.select_all(action='DESELECT')
    curve=bpy.data.curves.new('Documentary typography','FONT');curve.body=text;curve.size=size;curve.resolution_u=2
    obj=bpy.data.objects.new(text,curve);bpy.context.scene.collection.objects.link(obj)
    obj.location=(x,-.151,y);obj.rotation_euler=(math.pi/2,0,0)
    finish(obj,text,material,part);bpy.context.view_layer.update()
    if obj.dimensions.x>width:obj.scale*=width/obj.dimensions.x
    bpy.context.view_layer.objects.active=obj;obj.select_set(True);bpy.ops.object.convert(target='MESH');obj.select_set(False)

def tile(x,y,w,h,text,part='optical-core',colour='ceramic'):
    box(x,y,w,h,colour,depth=.055,z=.083,part=part)
    word(text,x-w/2+.07,y-.045,.115,w-.14,part,'graphite' if colour=='ceramic' else 'ceramic')

def connect(points,colour='amber'):
    line(points,colour,.025,z=.037,part='optical-lenses')

def sequence(names,y=1.7):
    step=3.85/len(names);w=step-.15
    for i,name in enumerate(names):
        x=-1.925+step*(i+.5);tile(x,y,w,.56,name)
        if i:connect([(x-step+w/2,y),(x-w/2,y)])

